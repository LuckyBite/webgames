// Сколько монет здание приносит владельцу за круг из P игроков — без учёта соседства.
// Это же число служит ИИ оценкой «выгодности», и по нему считается окупаемость.
export function incomePerRound(b, players, mods = {}) {
  const hits = b.num.length / RULES.diceFaces;      // доля бросков, попадающих в номер
  const pay = b.pay + (b.cls === 'мастерская' ? (mods.workshopBonus || 0)
                     : b.cls === 'промысел'   ? (mods.tradeBonus || 0) : 0);
  if (!b.num.length) return 0;
  if (b.cls === 'мастерская') return hits * pay;                 // один свой бросок за круг
  if (b.cls === 'рынок')      return hits * pay * (players - 1); // три чужих броска
  return hits * pay * players;                                   // промысел ловит все броски
}

// Окупаемость в СВОИХ ходах: круг = один свой ход.
export function paybackRounds(b, players) {
  const inc = incomePerRound(b, players);
  return inc > 0 ? b.cost / inc : Infinity;
}

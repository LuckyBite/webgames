export function nextScene(s) {
  return SCENES.find(sc => !s.story.seen[sc.id] && sc.when(s)) || null;
}

// Реплики сцены на сейчас: условные — только когда условие выполнено.
export function sceneLines(s, sc) {
  return sc.lines.filter(l => !l.when || l.when(s)).map(l => ({ who: l.who, text: storyText(s, tr(l.text)), log: !!l.log }));
}

// Сцена показана — её последствия: пришедший искатель, нанятый помощник, открытые маршруты.
export function playScene(s, id) {
  const sc = SCENES.find(x => x.id === id);
  if (!sc || s.story.seen[id]) return false;
  s.story.seen[id] = true;
  if (sc.join) s.seekers[sc.join].joined = true;
  if (sc.hire) Object.assign(s.staff[sc.hire], { joined: true, day: s.day });
  for (const f of sc.flags || []) s.story.flags[f] = true;
  return true;
}


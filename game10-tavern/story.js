const flag = (s, f) => !!s.story.flags[f];
const ln = (who, text, when) => ({ who, text, when });

export function chapterOf(s) {
  return CHAPTERS.find(c => c.id === s.story.chapter) || null;
}

// {guests}, {goal} — из пира текущей главы.
export function storyText(s, text) {
  const f = FEASTS[chapterOf(s)?.feast];
  return text.replace(/\{(\w+)\}/g, (m, k) => (f && k in f ? String(f[k]) : m));
}

// Гости с загадками — с главы 2: к этому времени рука набита на обычных заказах.
export const riddlesOn = s => s.story.chapter >= 2;

// Окна показывают сюжет (спека, «Графика»): туман густеет от главы к главе, после финала —
// рассвет. fog — 0..1, насколько стекло затянуто.
const FOG = [0.35, 0.3, 0.6, 0.8, 0.95];
export function skyOf(s) {
  const dawn = !!s.story.flags.chapter5;
  return { fog: dawn ? 0.15 : FOG[Math.min(FOG.length, s.story.chapter) - 1], dawn };
}

// ---------- глава и пир ----------

// Пир главы готов: сюжетная находка есть и славы хватает (спека: глава продвигается
// находкой, славой и пиром разом). Пройденный пир переводит главу дальше. После неудачной
// попытки слава больше не нужна: провал сам отнимает славу (голодные гости) и иначе
// уводил бы пир за порог — а спека обещает «назавтра пир снова».
export function feastReady(s) {
  const ch = chapterOf(s);
  return !!ch && flag(s, ch.find) && (s.fame >= ch.fame || s.story.feastTries > 0);
}

// Пир для смены; ease — прибавка терпения за прошлые неудачи.
export function feastSetup(s) {
  if (!feastReady(s)) return null;
  const id = chapterOf(s).feast, f = FEASTS[id];
  return { id, guests: f.guests, goal: f.goal, gap: f.gap, items: f.items, patience: f.patience, ease: Math.min(f.easierMax, f.easier * s.story.feastTries) };
}


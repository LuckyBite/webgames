// Итог пира: удача — награда и следующая глава (она идёт со следующего дня); провал —
// попытка в счёт и совет Жара. Возвращает, что вышло, для отчёта; обычный день — null.
export function applyFeast(s, sum) {
  if (!sum.feast) return null;
  const f = FEASTS[sum.feast.id], ch = chapterOf(s);
  const out = { name: f.name, ok: sum.served >= sum.feast.goal, served: sum.served, goal: sum.feast.goal, guests: sum.feast.guests };
  if (out.ok) {
    s.coins += f.reward.coins;
    s.fame += f.reward.fame;
    s.story.flags[`chapter${ch.id}`] = true;
    s.story.chapter += 1;
    s.story.chapterAt = s.day + 1;
    s.story.feastTries = 0;
    out.reward = { ...f.reward };
    out.last = ch.id === CHAPTERS[CHAPTERS.length - 1].id;
  } else {
    out.hint = FEAST_HINTS[s.story.feastTries % FEAST_HINTS.length];
    s.story.feastTries += 1;
  }
  return out;
}

// Строка цели в шапке утра.
export function goalText(s) {
  const ch = chapterOf(s);
  if (!ch) return tr('Таверна открыта');
  if (feastReady(s)) return s.story.feastTries ? tf('Пир, попытка {n}', { n: s.story.feastTries + 1 }) : tr('Сегодня пир');
  if (flag(s, ch.find)) return tf('Слава для пира: {fame}/{need}', { fame: s.fame, need: ch.fame });
  const find = FINDS.find(f => f.id === ch.find), who = s.seekers[find.seeker];
  const def = SEEKERS.find(x => x.id === find.seeker), route = ROUTES.find(r => r.id === find.route);
  if (!who.joined || !flag(s, route.flag)) return tf('Глава {n}: {name}', { n: ch.id, name: tr(ch.name) });
  if (who.state === 'home') return tf('Отправь {who} {to}', { who: tr(def.acc), to: tr(route.to) });
  if (who.state === 'away') return tf('{name}: в походе', { name: tr(def.name) });
  return tf('{name}: забери добычу', { name: tr(def.name) });
}


// скриптом story-md.mjs): правка здесь — правка там.
//
// Трактирщик в текстах без рода и имени: без «хозяин», без прошедшего времени и
// прилагательных о нём (спека, «Мир и история»). Прежний трактирщик зовётся по имени: Ольт.

